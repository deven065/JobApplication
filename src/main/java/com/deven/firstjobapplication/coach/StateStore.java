package com.deven.firstjobapplication.coach;

import com.deven.firstjobapplication.coach.Models.*;
import com.fasterxml.jackson.databind.ObjectMapper;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Component;
import org.springframework.transaction.annotation.Transactional;

import java.util.List;
import java.util.Map;
import java.util.function.Function;
import java.util.stream.Collectors;

/** Small local persistence layer for the single-user prototype. */
@Component
public class StateStore {
    private final JdbcTemplate jdbc;
    private final ObjectMapper json = new ObjectMapper().findAndRegisterModules();

    public StateStore(JdbcTemplate jdbc) {
        this.jdbc = jdbc;
        jdbc.execute("CREATE TABLE IF NOT EXISTS coach_jobs (id VARCHAR(128) PRIMARY KEY, payload TEXT NOT NULL)");
        jdbc.execute("CREATE TABLE IF NOT EXISTS coach_watches (repository VARCHAR(255) PRIMARY KEY, payload TEXT NOT NULL)");
        jdbc.execute("CREATE TABLE IF NOT EXISTS coach_assessments (assessment_key VARCHAR(512) PRIMARY KEY, branch VARCHAR(255) NOT NULL, payload TEXT NOT NULL)");
        jdbc.execute("CREATE TABLE IF NOT EXISTS coach_history (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, assessment_key VARCHAR(512) NOT NULL, payload TEXT NOT NULL)");
    }

    public Map<String, JobRequirement> jobs() {
        return jdbc.queryForList("SELECT payload FROM coach_jobs", String.class).stream()
                .map(value -> read(value, JobRequirement.class)).collect(Collectors.toMap(JobRequirement::id, Function.identity()));
    }
    @Transactional public void saveJob(JobRequirement job) {
        jdbc.update("DELETE FROM coach_jobs WHERE id = ?", job.id());
        jdbc.update("INSERT INTO coach_jobs (id, payload) VALUES (?, ?)", job.id(), write(job));
    }
    public List<RepoRegistration> watches() {
        return jdbc.queryForList("SELECT payload FROM coach_watches", String.class).stream()
                .map(value -> read(value, RepoRegistration.class)).toList();
    }
    @Transactional public void saveWatch(RepoRegistration watch) {
        jdbc.update("DELETE FROM coach_watches WHERE repository = ?", watch.repository());
        jdbc.update("INSERT INTO coach_watches (repository, payload) VALUES (?, ?)", watch.repository(), write(watch));
    }
    public List<SavedAssessment> assessments() {
        return jdbc.query("SELECT branch, payload FROM coach_assessments", (row, index) ->
                new SavedAssessment(row.getString("branch"), read(row.getString("payload"), Assessment.class)));
    }
    @Transactional public void saveAssessment(String key, String branch, Assessment assessment) {
        String payload = write(assessment);
        jdbc.update("DELETE FROM coach_assessments WHERE assessment_key = ?", key);
        jdbc.update("INSERT INTO coach_assessments (assessment_key, branch, payload) VALUES (?, ?, ?)", key, branch, payload);
        jdbc.update("INSERT INTO coach_history (assessment_key, payload) VALUES (?, ?)", key, payload);
    }
    public List<Assessment> history(String key) {
        return jdbc.query("SELECT payload FROM coach_history WHERE assessment_key = ? ORDER BY id DESC LIMIT 20",
                (row, index) -> read(row.getString("payload"), Assessment.class), key);
    }
    /** Removes a job and every scan history entry recorded for it. */
    public void deleteJob(String jobId) {
        jdbc.update("DELETE FROM coach_jobs WHERE id = ?", jobId);
        jdbc.update("DELETE FROM coach_history WHERE assessment_key LIKE ?", jobId + "|%");
    }
    public void deleteHistory(String jobId) { jdbc.update("DELETE FROM coach_history WHERE assessment_key LIKE ?", jobId + "|%"); }
    public void deleteWatch(String repository) { jdbc.update("DELETE FROM coach_watches WHERE repository = ?", repository); }
    public void deleteCurrentAssessments(String jobId) {
        jdbc.update("DELETE FROM coach_assessments WHERE assessment_key LIKE ?", jobId + "|%");
    }
    public record SavedAssessment(String branch, Assessment assessment) { }

    private String write(Object value) {
        try { return json.writeValueAsString(value); }
        catch (Exception error) { throw new IllegalStateException("Could not save assessment data", error); }
    }
    private <T> T read(String value, Class<T> type) {
        try { return json.readValue(value, type); }
        catch (Exception error) { throw new IllegalStateException("Could not read saved assessment data", error); }
    }
}
